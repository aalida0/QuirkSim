#!/usr/bin/env python3
"""Recover NNPDF replica uncertainty from a completed MG5_aMC 3.5.1 NLO run.

When Python LHAPDF bindings are absent, MG5 can still integrate with the
compiled LHAPDF interface but reports "combination method unknown". Its
`scale_pdf_dependence.dat` files nevertheless store per-member integrated
cross sections. Reproduce MG5 3.5.1's combination of these files using its
original job-status weights, without any LHAPDF Python import.

Only the central NNPDF40_nlo_as_01180 (LHAPDF 331700; 101 members) is
supported. The uncertainty is the 68%-CL Monte Carlo-replica spread and
does NOT include alpha_s, EW, scheme or scale uncertainties.

IMPORTANT: the active SubProcesses/job_status.pkl and variations files
are overwritten by subsequent runs in the same MG5 output directory.
Use this script immediately after the run being analysed. It checks that
the reconstructed PDF central value matches the saved run central value.
"""
from __future__ import annotations

import argparse
import math
import pickle
import re
import statistics
from pathlib import Path


SET_NAME = "NNPDF40_nlo_as_01180"
SET_ID = 331700
EXPECTED_MEMBERS = 101


def read_pdf_members(path: Path) -> list[float]:
    """Read the first PDF-set variation using MG5's three-line layout.

    After 'pdf variations:' MG5 writes one metadata line then one line
    containing all 101 member cross sections, in their original order.
    """
    with path.open(encoding="utf-8") as stream:
        for line in stream:
            if "pdf variations:" in line.lower():
                metadata = next(stream, None)
                values_line = next(stream, None)
                if metadata is None or values_line is None:
                    raise ValueError(f"Incomplete PDF variations block: {path}")
                tokens = metadata.split()
                if not tokens or tokens[0] != SET_NAME:
                    raise ValueError(
                        f"Expected PDF set {SET_NAME} in {path}, got {metadata.strip()!r}"
                    )
                try:
                    values = [float(v.replace("D", "E").replace("d", "e"))
                              for v in values_line.split()]
                except ValueError as exc:
                    raise ValueError(f"Non-numeric PDF member weight in {path}") from exc
                if len(values) != EXPECTED_MEMBERS:
                    raise ValueError(
                        f"Expected {EXPECTED_MEMBERS} PDF members, got "
                        f"{len(values)} in {path}; check reweight_PDF and LHAID"
                    )
                if not all(math.isfinite(v) for v in values):
                    raise ValueError(f"Non-finite PDF weights in {path}")
                return values
    raise ValueError(f"No 'pdf variations:' block in {path}")


def read_central_from_log(path: Path) -> float:
    """Read the final MG5 total cross section from the provided run log."""
    text = path.read_text(encoding="utf-8", errors="replace")
    xsecs = re.findall(
        r"Total cross section:\s*([+-]?(?:\d+(?:\.\d*)?|\.\d+)"
        r"(?:[eEdD][+-]?\d+)?)\s*\+\-",
        text,
    )
    if not xsecs:
        raise ValueError(f"Did not find 'Total cross section:' in {path}")
    return float(xsecs[-1].replace("D", "E"))


def resolve_job_directory(process: Path, job: dict) -> Path:
    raw = Path(job["dirname"])
    if raw.is_absolute():
        folder = raw.resolve()
    elif str(raw).startswith("SubProcesses/"):
        folder = (process / raw).resolve()
    else:
        folder = (process / "SubProcesses" / raw).resolve()
    parent = (process / "SubProcesses").resolve()
    if not folder.is_relative_to(parent):
        raise ValueError(f"Job path outside process SubProcesses: {folder}")
    return folder


def pdf_replica_summary(
    process: Path, *,
    expected_central: float | None = None,
    relative_central_tolerance: float = 0.01,
) -> dict:
    process = process.resolve()
    job_file = process / "SubProcesses" / "job_status.pkl"
    if not job_file.is_file():
        raise FileNotFoundError(
            f"Missing {job_file}. The saved NLO job weights are required."
        )
    # Pickle can execute arbitrary code. Only use the local, trusted
    # MG5 job-status file generated by your own run.
    with job_file.open("rb") as f:
        jobs = pickle.load(f)
    if not isinstance(jobs, list) or not jobs:
        raise ValueError("Expected non-empty list of NLO integration jobs")
    total = [0.0] * EXPECTED_MEMBERS
    for job in jobs:
        if not isinstance(job, dict) or "wgt_frac" not in job:
            raise ValueError("Unexpected MG5 job-status layout")
        fraction = float(job["wgt_frac"])
        if not math.isfinite(fraction):
            raise ValueError("Non-finite wgt_frac in job_status.pkl")
        source = resolve_job_directory(process, job) / "scale_pdf_dependence.dat"
        vals = read_pdf_members(source)
        for i, v in enumerate(vals):
            total[i] += fraction * v

    central = total[0]
    if central <= 0:
        raise ValueError("Reconstructed central cross section must be positive")
    if expected_central is not None:
        mismatch = abs(central - expected_central) / expected_central
        if mismatch > relative_central_tolerance:
            raise ValueError(
                f"Wrong run / inconsistent weights: PDF-weight central={central:.8g} pb"
                f" differs from MG5 summary={expected_central:.8g} pb "
                f"by {mismatch:.2%}. Do not quote the uncertainty."
            )
    replicas = total[1:]
    mean = statistics.mean(replicas)
    # The standard NNPDF replica error is the RMS of 100 replicas.
    # Use sample standard deviation (Nrep-1), and report the population
    # convention as a cross-check (difference <0.5% for 100 replicas).
    spread = statistics.stdev(replicas)
    population_spread = statistics.pstdev(replicas)
    return {
        "central_pb": central,
        "replica_mean_pb": mean,
        "pdf_sigma_pb": spread,
        "pdf_sigma_percent": spread / central * 100,
        "pdf_sigma_population_pb": population_spread,
        "replica_central_shift_pb": mean - central,
        "members": len(total),
        "jobs": len(jobs),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--process", type=Path,
        default=Path("results/pp_dirac_triplet_13p6TeV_NLO_NNPDF40"),
    )
    parser.add_argument(
        "--run-log", type=Path,
        default=Path("results/triplet_nlo_uncertainties.log"),
        help="Log from the exact same NLO integration run.",
    )
    parser.add_argument("--nic", type=int, default=2)
    args = parser.parse_args()
    if args.nic < 1:
        parser.error("--nic must be positive")
    expected = read_central_from_log(args.run_log) if args.run_log else None
    result = pdf_replica_summary(args.process, expected_central=expected)
    print(f"NNPDF replica set: {SET_NAME} (LHAPDF {SET_ID})")
    print(f"NLO integration jobs: {result['jobs']}   members: {result['members']}")
    print(f"Reconstructed central: {result['central_pb']:.7f} pb")
    print(f"Replica mean:         {result['replica_mean_pb']:.7f} pb")
    print(f"68%-CL PDF RMS:       +/- {result['pdf_sigma_pb']:.7f} pb "
          f"({result['pdf_sigma_percent']:.3f}%)")
    print(f"Population RMS check: +/- {result['pdf_sigma_population_pb']:.7f} pb")
    print(f"Replicas mean - central: {result['replica_central_shift_pb']:+.7f} pb")
    print(f"For N_IC={args.nic} spectators: "
          f"{result['central_pb']*args.nic:.7f} +/- "
          f"{result['pdf_sigma_pb']*args.nic:.7f} pb (PDF only)")
    print("NOTE: excludes integration, scale, alpha_s, EW and infracolor systematics.")


if __name__ == "__main__":
    main()
